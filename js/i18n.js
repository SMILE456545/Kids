/* Строка на текущем языке; у шаблонов — подставляет параметры */
function tr(key, ...args) {
  const v = (STR[LANG] && STR[LANG][key] !== undefined) ? STR[LANG][key] : STR.ru[key];
  return typeof v === 'function' ? v(...args) : v;
}
/* Словари (животные, еда, фрукты…) на текущем языке */
function trd(dict, k) { const d = STR[LANG][dict] || STR.ru[dict]; return d[k] !== undefined ? d[k] : STR.ru[dict][k]; }
const trList = (arr, sep) => arr.join(tr(sep));

/* Обновить тексты в разметке */
function applyLang() {
  document.documentElement.lang = LANG;
  document.title = tr('gameTitle');
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = tr(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', tr(el.dataset.i18nAria));
  for (const f of LANG_LISTENERS) f();
}
const LANG_LISTENERS = [];
function onLang(f) { LANG_LISTENERS.push(f); }
function setLang(l) {
  LANG = l; try { localStorage.setItem('farm.lang', l); } catch (e) {}
  applyLang();
}
function nextLang() { setLang(LANGS[(LANGS.indexOf(LANG) + 1) % LANGS.length]); }
document.addEventListener('DOMContentLoaded', () => {
  applyLang();
  for (const id of ['setLang', 'titleLang']) { const b = document.getElementById(id); if (b) b.addEventListener('click', (e) => { e.stopPropagation(); nextLang(); }); }
});
